import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const partnersDir = join(__dirname, '..', 'public', 'partners');
const outFile = join(__dirname, '..', 'src', 'app', 'components', 'partners', 'partners-manifest.ts');

const IMAGE_EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.webp', '.svg']);

function toDisplayName(filename) {
  const cleaned = filename
    .replace(/\.(png|jpg|jpeg|webp|svg)$/i, '')
    .replace(/[a-f0-9]{16,}/gi, '')
    .replace(/[_\-]+/g, ' ')
    .replace(/\b\d{3,}\b/g, '')
    .replace(/\s+/g, ' ')
    .trim();

  if (!cleaned) return 'Partner';

  return cleaned
    .split(' ')
    .map((w) => (/[a-zа-яіїєʼ']/.test(w) && w === w.toLowerCase() ? w.charAt(0).toUpperCase() + w.slice(1) : w))
    .join(' ');
}

const files = readdirSync(partnersDir)
  .filter((f) => IMAGE_EXTENSIONS.has(extname(f).toLowerCase()))
  .sort((a, b) => a.localeCompare(b));

const entries = files.map((f) => ({
  name: toDisplayName(f),
  logo: '/partners/' + encodeURIComponent(f),
}));

const content = `// AUTO-GENERATED by scripts/generate-partners-manifest.mjs — do not edit by hand.
// Regenerated from the contents of public/partners on every \`npm start\` / \`npm run build\`.

export interface PartnerLogo {
  name: string;
  logo: string;
}

export const PARTNERS_MANIFEST: PartnerLogo[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(outFile, content, 'utf-8');
console.log(`generate-partners-manifest: wrote ${entries.length} entries to ${outFile}`);
